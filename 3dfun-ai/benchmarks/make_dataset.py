def _write_attribution(dataset: dict) -> None:
    """Human-readable provenance table for every image in the dataset."""
    lines = ["# Dataset attribution", "",
             "Generated automatically by `benchmarks/make_dataset.py`; do not edit by hand.",
             "", "## Synthetic split (analytically defined geometry, CC0-1.0)", "",
             "| id | reference triangles | watertight | source |",
             "| --- | --- | --- | --- |"]
    for e in dataset["entries"]:
        if e["split"] == "synthetic":
            lines.append(f"| `{e['id']}` | {e['gt_triangles']} | {e['gt_watertight']} | "
                         f"analytic surface generated in-repo |")
    lines += ["", "## Real-photograph split", "",
              "| id | title | creator | host | licence | link |",
              "| --- | --- | --- | --- | --- | --- |"]
    for e in dataset["entries"]:
        if e["split"] == "real":
            a = e.get("attribution", {})
            lines.append(f"| `{e['id']}` | {a.get('title','-')} | {a.get('creator','-')} | "
                         f"{e.get('source','-')} | {e['license']} | {a.get('url','-')} |")
    lines += ["", "Photographs are cropped/resized only; no geometric editing was applied "
                  "to the inputs.", ""]
