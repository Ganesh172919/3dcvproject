def _write_png(path: Path, img: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(path), img)


def _resize_long_side(img: np.ndarray, long_side: int) -> np.ndarray:
    """Area-average resize so the longest side is ``long_side`` pixels."""
    h, w = img.shape[:2]
    scale = long_side / float(max(h, w))
    if abs(scale - 1.0) < 1e-6:
        return img
    interp = cv2.INTER_AREA if scale < 1.0 else cv2.INTER_CUBIC
    return cv2.resize(img, (max(1, int(round(w * scale))), max(1, int(round(h * scale)))),
                      interpolation=interp)


def _flatten_checker_alpha(img: np.ndarray) -> np.ndarray:
    """Replace a baked-in transparency checkerboard with a plain white ground.

    A few public-domain PNG stickers are distributed with the checkerboard
    flattened into the pixels instead of a real alpha channel. Those two grey
    levels are detected and replaced by white, so the input looks like an
    ordinary photograph of the object on a plain background.
    """
    if img.ndim != 3 or img.shape[2] != 3:
        return img
    grey = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    near = np.zeros(grey.shape, bool)
    for level in (238, 255):
        near |= np.abs(grey.astype(np.int16) - level) <= 2
    uniform = (img.max(axis=2).astype(np.int16)
               - img.min(axis=2).astype(np.int16)) <= 3
    mask = near & uniform
    if mask.mean() < 0.15:                    # ordinary photograph, leave it alone
        return img
    out = img.copy()
    out[mask] = 255
    # soften the replacement boundary so no hard checker edge survives
    soft = cv2.GaussianBlur(mask.astype(np.float32), (5, 5), 0)[:, :, None]
    blend = np.clip(soft * 1.6, 0, 1) * mask[:, :, None]
    out = (out.astype(np.float32) * (1 - blend) + 255.0 * blend).astype(np.uint8)
    return out


def _write_obj(path: Path, vertices: np.ndarray, faces: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# 3DFUN AI evaluation reference geometry\n")
        for v in vertices:
            fh.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for f in faces:
            fh.write(f"f {f[0] + 1} {f[1] + 1} {f[2] + 1}\n")


def _sample_mesh(v: np.ndarray, f: np.ndarray, count: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    """Area-weighted surface resampling, used to build reference meshes."""
    rng = np.random.default_rng(seed)
    tri = v[f]
    area = 0.5 * np.linalg.norm(np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0]), axis=1)
    idx = rng.choice(len(f), size=max(count, len(f)), p=area / area.sum())
    u, s = rng.random(len(idx)), rng.random(len(idx))
    flip = u + s > 1
    u[flip], s[flip] = 1 - u[flip], 1 - s[flip]
    pts = tri[idx, 0] * (1 - u - s)[:, None] + tri[idx, 1] * u[:, None] + tri[idx, 2] * s[:, None]

    # weld onto a coarse grid so the sampled cloud becomes a proper triangle mesh
    key = np.round(pts / 0.012).astype(np.int64)
    uniq, inverse = np.unique(key, axis=0, return_inverse=True)
    # rebuild faces from the original triangles using welded indices
    ai = inverse[idx * 3 + 0] if False else None
    verts = np.zeros_like(uniq, dtype=np.float64)
    for i, k in enumerate(uniq):
        verts[i] = key[i] * 0.012
    faces = np.column_stack([inverse[np.arange(0, len(idx) * 3, 3)],
                             inverse[np.arange(1, len(idx) * 3, 3)],
                             inverse[np.arange(2, len(idx) * 3, 3)]])
    faces = faces[(faces[:, 0] != faces[:, 1]) & (faces[:, 1] != faces[:, 2]) & (faces[:, 0] != faces[:, 2])]
    return verts, faces.astype(np.int64)


YAW_DEG, PITCH_DEG = 12.0, 14.0


def _rot_matrix(yaw_deg: float = YAW_DEG, pitch_deg: float = PITCH_DEG) -> np.ndarray:
    y, p = np.radians(yaw_deg), np.radians(pitch_deg)
    ry = np.array([[np.cos(y), 0, np.sin(y)], [0, 1, 0], [-np.sin(y), 0, np.cos(y)]])
    rx = np.array([[1, 0, 0], [0, np.cos(p), -np.sin(p)], [0, np.sin(p), np.cos(p)]])
    return rx @ ry


def _rotate(v: np.ndarray, yaw_deg: float = YAW_DEG, pitch_deg: float = PITCH_DEG) -> np.ndarray:
    """Fixed object pose so the reference view shows a little of the top/side."""
    return v @ _rot_matrix(yaw_deg, pitch_deg).T


def _zbuffer_render(v: np.ndarray, f: np.ndarray, albedo: tuple[int, int, int],
                    size: int = RES, return_camera: bool = False):
    """Z-buffered Lambert/Blinn render of the reference surface.

    A depth buffer (not painter's ordering) prevents the silhouette and coplanar
    face artefacts that fillPoly ordering produces, so the synthetic inputs look
    like photographs of matte plastic rather than shaded wireframes.
    """
    v = _rotate(v)
    tri = v[f]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    area = 0.5 * np.linalg.norm(fn, axis=1)
    fn = fn / np.maximum(np.linalg.norm(fn, axis=1, keepdims=True), 1e-9)

    vn = np.zeros_like(v)
    for c in range(3):
        np.add.at(vn, f[:, c], fn * area[:, None])
    vn /= np.maximum(np.linalg.norm(vn, axis=1, keepdims=True), 1e-9)

    uv = np.stack([v[:, 0], -v[:, 1]], axis=1)
    lo, hi = uv.min(axis=0), uv.max(axis=0)
    span = float(max(hi - lo))
    scale = size * 0.70 / max(span, 1e-9)
    centre = (lo + hi) / 2.0
    scr = (uv - centre) * scale + size / 2.0

    z = np.full((size, size), -np.inf, np.float32)
    img = np.full((size, size, 3), 247.0, np.float32)
    light = np.array([-0.42, 0.62, 0.66]); light /= np.linalg.norm(light)
    view = np.array([0.0, 0.0, 1.0])
    half = light + view; half /= np.linalg.norm(half)
    face_n = vn[f].mean(axis=1)
    face_n /= np.maximum(np.linalg.norm(face_n, axis=1, keepdims=True), 1e-9)
    lam = 0.44 + 0.50 * np.clip(face_n @ light, 0, 1) + 0.10 * np.clip(face_n @ view, 0, 1)
    spec = np.clip(face_n @ half, 0, 1) ** 18 * 0.20
    base = np.array(albedo, float) / 255.0

    depth = tri[:, :, 2].mean(axis=1)
    order = np.argsort(depth)                     # cheap early rejection order
    for i in order:
        x0, y0 = scr[f[i], 0], scr[f[i], 1]
        xmin, xmax = int(max(0, np.floor(x0.min()))), int(min(size - 1, np.ceil(x0.max())))
        ymin, ymax = int(max(0, np.floor(y0.min()))), int(min(size - 1, np.ceil(y0.max())))
        if xmax < xmin or ymax < ymin:
            continue
        xs, ys = np.meshgrid(np.arange(xmin, xmax + 1) + 0.5, np.arange(ymin, ymax + 1) + 0.5)
        det = ((y0[1] - y0[2]) * (x0[0] - x0[2]) + (x0[2] - x0[1]) * (y0[0] - y0[2]))
        if abs(det) < 1e-12:
            continue
        w0 = ((y0[1] - y0[2]) * (xs - x0[2]) + (x0[2] - x0[1]) * (ys - y0[2])) / det
        w1 = ((y0[2] - y0[0]) * (xs - x0[2]) + (x0[0] - x0[2]) * (ys - y0[2])) / det
        w2 = 1.0 - w0 - w1
        inside = (w0 >= -1e-6) & (w1 >= -1e-6) & (w2 >= -1e-6)
        if not inside.any():
            continue
        zval = w0 * tri[i, 0, 2] + w1 * tri[i, 1, 2] + w2 * tri[i, 2, 2]
        sub_z = z[ymin:ymax + 1, xmin:xmax + 1]
        mask = inside & (zval > sub_z)
        if not mask.any():
            continue
        sub_z[mask] = zval[mask]
        colour = base * lam[i] + spec[i]
        colour = colour * (0.94 + 0.06 * np.clip(face_n[i][1] + 1.0, 0, 2.0))
        img[ymin:ymax + 1, xmin:xmax + 1][mask] = np.clip(colour * 255, 0, 255)

    out = cv2.GaussianBlur(np.clip(img, 0, 255).astype(np.uint8), (3, 3), 0.55)
    if not return_camera:
        return out
    rot = _rot_matrix()
    return out, {"rotation": rot.tolist(), "scale": float(scale),
                 "centre_uv": centre.tolist(), "size": int(size),
                 "z_min": float(z.min()), "z_max": float(z.max())}


