def _resample_for_gt(v: np.ndarray, f: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Subdivide + weld so a 12-triangle cube becomes a dense reference shell."""
    import trimesh

    mesh = trimesh.Trimesh(vertices=v, faces=f, process=True)
    for _ in range(3):
        mesh = mesh.subdivide()
        mesh.merge_vertices()
    mesh.update_faces(mesh.nondegenerate_faces())
    mesh.remove_unreferenced_vertices()
    return np.asarray(mesh.vertices, float), np.asarray(mesh.faces, np.int64)


