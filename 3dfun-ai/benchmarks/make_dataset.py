"""Build the evaluation dataset: images + reference geometry.

Two complementary splits are produced under ``benchmarks/data/``:

``synthetic``  Procedurally defined scenes whose ground-truth surface is
               *known analytically* (box, prism, cylinder, staircase, ...). A
               reference mesh with several thousand triangles is generated by
               sampling that analytic surface, so Chamfer distance, F-score,
               volumetric IoU and normal consistency are all well defined. The
               photographed input is a shaded render of the same geometry, which
               is what a user would upload.

``real``       Photographs of physical objects (``engine/testdata/sneaker.png``
               shipped with the repository and the other photographs in
               ``benchmarks/data/real/``). No metric ground truth exists for a
               single photograph of a real object, so these images are evaluated
               on the metrics that do not need reference geometry (runtime,
               memory, watertightness, UV coverage, self-consistency between the
               input silhouette and the re-rendered silhouette) and are marked
               ``gt: null`` in ``dataset.json``.

Every entry records its source and licence. Nothing outside this repository is
downloaded, so the dataset is reproducible offline.
"""
